static void test_panic_fires_after_the_full_duration(void) {
    tc_state s;
    tc_init(&s);
    tc_step(&s, HOME_DOWN, 1000);
    tc_out armed = tc_step(&s, SELECT_DOWN, 1100);
    CHECK(count_of(armed, TC_PANIC) == 0);
    CHECK(armed.deadline_ms == 1100 + TC_PANIC_MS);

    tc_out early = tc_step(&s, tick_event(), 1100 + TC_PANIC_MS - 1);
    CHECK(count_of(early, TC_PANIC) == 0);

    tc_out boom = tc_step(&s, tick_event(), 1100 + TC_PANIC_MS);
    CHECK(count_of(boom, TC_PANIC) == 1);
}

static void test_panic_is_cancelled_by_releasing_a_key(void) {
    tc_state s;
    tc_init(&s);
    tc_step(&s, HOME_DOWN, 1000);
    tc_step(&s, SELECT_DOWN, 1100);
    tc_out released = tc_step(&s, SELECT_UP, 1200);
    CHECK(released.deadline_ms == -1);

    tc_out later = tc_step(&s, tick_event(), 1100 + TC_PANIC_MS + 1000);
    CHECK(count_of(later, TC_PANIC) == 0);
}

/* ---- Finding 1: evdev autorepeat (value == 2) ---- */

static void test_x_autorepeat_does_not_delay_hold(void) {
    tc_state s;
    tc_init(&s);
    tc_step(&s, AYN_DOWN, 1000);
    tc_out down = tc_step(&s, X_DOWN, 1050);
    CHECK(down.deadline_ms == 1050 + TC_HOLD_MS);

    /* Autorepeats arrive roughly every ~33ms while X stays physically down.
       None of them may push the hold deadline back out. */
    tc_out r1 = tc_step(&s, X_REPEAT, 1083);
    CHECK(r1.n == 1);
    CHECK(r1.items[0].kind == TC_SWALLOW);
    CHECK(r1.items[0].ev.code == TC_CODE_X);
    CHECK(r1.deadline_ms == 1050 + TC_HOLD_MS);

    tc_out r2 = tc_step(&s, X_REPEAT, 1116);
    CHECK(r2.deadline_ms == 1050 + TC_HOLD_MS);

    tc_out r3 = tc_step(&s, X_REPEAT, 1300);
    CHECK(r3.deadline_ms == 1050 + TC_HOLD_MS);

    /* It still fires at the ORIGINAL deadline despite all the repeats. */
    tc_out fired = tc_step(&s, tick_event(), 1050 + TC_HOLD_MS);
    CHECK(count_of(fired, TC_FIRE) == 1);
}

static void test_autorepeat_of_swallowed_key_is_swallowed(void) {
    tc_state s;
    tc_init(&s);
    tc_step(&s, AYN_DOWN, 1000);
    tc_step(&s, X_DOWN, 1050);
    tc_step(&s, tick_event(), 1050 + TC_HOLD_MS);  /* rule fires; X is still held */

    /* The kernel keeps repeating X while it's physically down. The original
       press was swallowed and the rule already fired, so the repeat must stay
       swallowed too -- the app must never see it. */
    tc_out o = tc_step(&s, X_REPEAT, 1050 + TC_HOLD_MS + 33);
    CHECK(o.n == 1);
    CHECK(o.items[0].kind == TC_SWALLOW);
    CHECK(o.items[0].ev.code == TC_CODE_X);
}

static void test_autorepeat_of_forwarded_key_is_forwarded(void) {
    tc_state s;
    tc_init(&s);
    /* AYN is not held, so X-down is forwarded, not swallowed. */
    tc_step(&s, X_DOWN, 1000);

    tc_out o = tc_step(&s, X_REPEAT, 1033);
    CHECK(o.n == 1);
    CHECK(o.items[0].kind == TC_FORWARD);
    CHECK(o.items[0].ev.code == TC_CODE_X);
    CHECK(o.deadline_ms == -1);
}

static void test_ayn_autorepeat_is_swallowed_and_does_not_reset_session(void) {
    tc_state s;
    tc_init(&s);
    tc_step(&s, AYN_DOWN, 1000);
    tc_step(&s, X_DOWN, 1050);  /* arms the hold */

    tc_out r = tc_step(&s, AYN_REPEAT, 1100);
    CHECK(r.n == 1);
    CHECK(r.items[0].kind == TC_SWALLOW);
    CHECK(r.items[0].ev.code == TC_CODE_AYN);
    /* The live session -- and its armed deadline -- must survive untouched. */
    CHECK(r.deadline_ms == 1050 + TC_HOLD_MS);

    tc_out fired = tc_step(&s, tick_event(), 1050 + TC_HOLD_MS);
    CHECK(count_of(fired, TC_FIRE) == 1);
}

/* ---- Finding 2: panic cannot be shadowed by a due rule in the same step ---- */

static void test_panic_is_not_shadowed_by_a_due_rule_in_the_same_step(void) {
    tc_state s;
    tc_init(&s);

    /* Arm the AYN+X hold first. */
    tc_step(&s, AYN_DOWN, 1000);
    tc_out x = tc_step(&s, X_DOWN, 1050);
    CHECK(count_of(x, TC_SWALLOW) == 1);  /* hold_deadline_ms = 1450 */

    /* Press Home then Select while AYN is still held. This goes through the
       "any other control" branch, which synthesizes AYN-down and sets
       ayn_emitted -- but that does not touch the hold deadline already armed
       above, per the brief's warning about this interaction. */
    tc_step(&s, HOME_DOWN, 1100);
    tc_out armed = tc_step(&s, SELECT_DOWN, 1150);  /* panic_deadline_ms = 5150 */
    CHECK(count_of(armed, TC_PANIC) == 0);

    /* Jump straight to a single tick where BOTH deadlines (1450 and 5150) are
       already due -- no intermediate tick in between. Only panic may fire. */
    tc_out boom = tc_step(&s, tick_event(), 1150 + TC_PANIC_MS);
    CHECK(boom.n == 1);
    CHECK(count_of(boom, TC_PANIC) == 1);
    CHECK(count_of(boom, TC_FIRE) == 0);
}

static void test_panic_keys_still_reach_the_app(void) {
    /* Home and Select are not modifiers in M1 -- no rule uses them -- so they
       belong to the app. The derived-modifier principle, in one test. */
    tc_state s;
    tc_init(&s);
    tc_out o = tc_step(&s, HOME_DOWN, 1000);
    CHECK(count_of(o, TC_FORWARD) == 1);
    tc_out u = tc_step(&s, HOME_UP, 1100);
    CHECK(count_of(u, TC_FORWARD) == 1);
}

