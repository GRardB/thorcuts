#include "matcher.h"

#include <string.h>

static void push(tc_out *o, tc_kind kind, tc_event ev, uint16_t rule_id) {
    if (o->n >= TC_MAX_DECISIONS) return;
    o->items[o->n].kind = kind;
    o->items[o->n].ev = ev;
    o->items[o->n].rule_id = rule_id;
    o->n++;
}

static tc_event key_event(uint8_t dev, uint16_t code, int32_t value) {
    tc_event e;
    e.dev = dev;
    e.type = TC_EV_KEY;
    e.code = code;
    e.value = value;
    return e;
}

static tc_event no_event(void) {
    tc_event e;
    e.dev = 0;
    e.type = 0;
    e.code = 0;
    e.value = 0;
    return e;
}

static bool is_key(tc_event e, uint8_t dev, uint16_t code) {
    return e.dev == dev && e.type == TC_EV_KEY && e.code == code;
}

/* evdev key values: 1 = press (the down transition), 0 = release, and
   2 = autorepeat -- generated by the kernel for EV_REP devices while a key
   stays physically down. An autorepeat is not a fresh transition: it must
   never arm, re-arm, or clear a deadline, and must never change state. */
static bool is_down(tc_event e) {
    return e.type == TC_EV_KEY && e.value == 1;
}

static bool is_repeat(tc_event e) {
    return e.type == TC_EV_KEY && e.value == 2;
}

/* The sooner of two deadlines, treating -1 as "none". */
static int64_t earlier(int64_t a, int64_t b) {
    if (a < 0) return b;
    if (b < 0) return a;
    return a < b ? a : b;
}

void tc_init(tc_state *s) {
    memset(s, 0, sizeof *s);
    s->hold_deadline_ms = -1;
    s->panic_deadline_ms = -1;
}

/* Arm or disarm the panic combo. These keys are NOT swallowed: with only an AYN
   rule in M1, Home and Select are not modifiers, so they belong to the app. */
static void track_panic(tc_state *s, tc_event ev, int64_t now_ms) {
    bool touched = false;
    if (is_key(ev, TC_DEV_PAD, TC_CODE_HOME)) {
        s->home_held = ev.value != 0;
        touched = true;
    }
    if (is_key(ev, TC_DEV_PAD, TC_CODE_SELECT)) {
        s->select_held = ev.value != 0;
        touched = true;
    }
    if (!touched) return;

    if (s->home_held && s->select_held) {
        if (s->panic_deadline_ms < 0) s->panic_deadline_ms = now_ms + TC_PANIC_MS;
    } else {
        s->panic_deadline_ms = -1;
    }
}

tc_out tc_step(tc_state *s, tc_event ev, int64_t now_ms) {
    tc_out o;
    memset(&o, 0, sizeof o);
    o.deadline_ms = -1;

    track_panic(s, ev, now_ms);

    /* Panic is checked BEFORE any rule, and cannot be shadowed by one. */
    if (s->panic_deadline_ms >= 0 && now_ms >= s->panic_deadline_ms) {
        push(&o, TC_PANIC, no_event(), 0);
        return o;  /* no deadline: main.c is on its way out */
    }

    if (ev.type == TC_EV_TICK) {
        if (s->hold_deadline_ms >= 0 && now_ms >= s->hold_deadline_ms) {
            s->hold_deadline_ms = -1;
            s->fired = true;
            push(&o, TC_FIRE, no_event(), TC_RULE_SWAP_SCREENS);
        }
        o.deadline_ms = earlier(s->hold_deadline_ms, s->panic_deadline_ms);
        return o;
    }

    /* ---- the AYN modifier ---- */
    if (is_key(ev, TC_DEV_GPIO, TC_CODE_AYN)) {
        if (is_down(ev)) {
            if (!s->ayn_held) {
                s->ayn_held = true;
                s->ayn_emitted = false;
                s->fired = false;
                s->x_swallowed = false;
                s->hold_deadline_ms = -1;
            }
            push(&o, TC_SWALLOW, ev, 0);
        } else if (is_repeat(ev)) {
            /* The modifier's press is always swallowed, so its autorepeat is
               too. State and deadlines are untouched. */
            push(&o, TC_SWALLOW, ev, 0);
        } else {
            bool fired = s->fired;
            bool emitted = s->ayn_emitted;
            s->ayn_held = false;
            s->ayn_emitted = false;
            s->fired = false;
            s->x_swallowed = false;
            s->hold_deadline_ms = -1;

            if (fired) {
                /* The combo did its job; the app sees none of it. */
                push(&o, TC_SWALLOW, ev, 0);
            } else if (emitted) {
                /* AYN-down already went down; close the pair. */
                push(&o, TC_SYNTH, key_event(TC_DEV_GPIO, TC_CODE_AYN, 0), 0);
            } else {
                /* A bare tap: hand the app the press it never saw. */
                push(&o, TC_SYNTH, key_event(TC_DEV_GPIO, TC_CODE_AYN, 1), 0);
                push(&o, TC_SYNTH, key_event(TC_DEV_GPIO, TC_CODE_AYN, 0), 0);
            }
        }
        o.deadline_ms = earlier(s->hold_deadline_ms, s->panic_deadline_ms);
        return o;
    }

    /* ---- X, the one bound button ---- */
    if (is_key(ev, TC_DEV_PAD, TC_CODE_X)) {
        if (is_down(ev)) {
            if (s->ayn_held && !s->fired && !s->ayn_emitted) {
                s->x_swallowed = true;
                s->hold_deadline_ms = now_ms + TC_HOLD_MS;
                push(&o, TC_SWALLOW, ev, 0);
            } else {
                push(&o, TC_FORWARD, ev, 0);
            }
        } else if (is_repeat(ev)) {
            /* Mirror whatever the press did. Never re-arm the hold deadline
               or re-evaluate the AYN/fired/emitted conditions here. */
            push(&o, s->x_swallowed ? TC_SWALLOW : TC_FORWARD, ev, 0);
        } else if (s->x_swallowed) {
            s->x_swallowed = false;
            s->hold_deadline_ms = -1;
            if (s->fired) {
                push(&o, TC_SWALLOW, ev, 0);
            } else {
                /* Released before the hold completed, so it was a tap. Give the app
                   the whole gesture, modifier first, in the order it expects. */
                if (!s->ayn_emitted) {
                    push(&o, TC_SYNTH, key_event(TC_DEV_GPIO, TC_CODE_AYN, 1), 0);
                    s->ayn_emitted = true;
                }
                push(&o, TC_SYNTH, key_event(TC_DEV_PAD, TC_CODE_X, 1), 0);
                push(&o, TC_SYNTH, key_event(TC_DEV_PAD, TC_CODE_X, 0), 0);
            }
        } else {
            push(&o, TC_FORWARD, ev, 0);
        }
        o.deadline_ms = earlier(s->hold_deadline_ms, s->panic_deadline_ms);
        return o;
    }

    /* ---- everything else ----
       A key going down while AYN is held that cannot complete M1's only rule
       means no rule can still match: hand the app the modifier it never saw,
       then the event itself. */
    if (is_down(ev) && s->ayn_held && !s->ayn_emitted && !s->fired) {
        push(&o, TC_SYNTH, key_event(TC_DEV_GPIO, TC_CODE_AYN, 1), 0);
        s->ayn_emitted = true;
    }
    push(&o, TC_FORWARD, ev, 0);
    o.deadline_ms = earlier(s->hold_deadline_ms, s->panic_deadline_ms);
    return o;
}
